#!/usr/bin/env bash
# ============================================================================
# update-proof-ledger.sh
#
# Generate or verify top-level proof transparency docs:
#   - PROOF_STATUS.md
#   - AXIOMS.md
#
# Usage:
#   bash scripts/update-proof-ledger.sh
#   bash scripts/update-proof-ledger.sh --check
# ============================================================================

set -euo pipefail

REPO_ROOT="$(git rev-parse --show-toplevel)"
COQ_DIR="$REPO_ROOT/02_FORMAL/coq"
COQ_PROJECT="$COQ_DIR/_CoqProject"
CHECK_MODE=0

if [ "${1:-}" = "--check" ]; then
  CHECK_MODE=1
fi

if [ ! -f "$COQ_PROJECT" ]; then
  echo "ERROR: missing $COQ_PROJECT"
  exit 1
fi

tmp_status="$(mktemp)"
tmp_axioms="$(mktemp)"
tmp_active_axiom_sites="$(mktemp)"
tmp_active_assumption_sites="$(mktemp)"
tmp_active_abort_sites="$(mktemp)"
trap 'rm -f "$tmp_status" "$tmp_axioms" "$tmp_active_axiom_sites" "$tmp_active_assumption_sites" "$tmp_active_abort_sites"' EXIT

mapfile -t active_coq_files < <(
  awk '
    {
      line=$0;
      sub(/^[ \t]+/, "", line);
      if (line ~ /^[#-]/ || line == "") next;
      split(line, tok, /[ \t]+/);
      if (tok[1] ~ /\.v$/) print tok[1];
    }
  ' "$COQ_PROJECT"
)

active_files_count="${#active_coq_files[@]}"
total_coq_files="$(find "$COQ_DIR" -name "*.v" -type f | wc -l | tr -d " ")"
inactive_files_count=$((total_coq_files - active_files_count))

active_qed=0
active_admitted=0
active_abort=0
active_axioms=0
active_assumptions=0
active_parameters=0

for rel in "${active_coq_files[@]}"; do
  path="$COQ_DIR/$rel"
  [ -f "$path" ] || continue

  # Keep Qed counting aligned with scripts/generate-metrics.sh.
  qed_hits="$(grep -c 'Qed\.' "$path" || true)"
  admitted_hits="$(grep -Ec '^[[:space:]]*Admitted\.' "$path" || true)"
  abort_hits="$(grep -Ec '^[[:space:]]*Abort\.' "$path" || true)"
  axiom_hits="$(grep -Ec '^[[:space:]]*Axiom[[:space:]]+' "$path" || true)"
  assumption_hits="$(grep -Ec '^[[:space:]]*Parameter[[:space:]]+val_rel_n_step_up[[:space:]]' "$path" || true)"
  # Total `Parameter` declarations — logically axioms; the documented Trusted
  # Computing Base (hardware/crypto interfaces). Surfaced for honesty.
  parameter_hits="$(grep -Ec '^[[:space:]]*Parameter[[:space:]]+' "$path" || true)"

  active_qed=$((active_qed + qed_hits))
  active_admitted=$((active_admitted + admitted_hits))
  active_abort=$((active_abort + abort_hits))
  active_axioms=$((active_axioms + axiom_hits))
  active_assumptions=$((active_assumptions + assumption_hits))
  active_parameters=$((active_parameters + parameter_hits))

  grep -nE '^[[:space:]]*Axiom[[:space:]]+' "$path" | sed "s|^|$rel:|" >> "$tmp_active_axiom_sites" || true
  grep -nE '^[[:space:]]*Parameter[[:space:]]+val_rel_n_step_up[[:space:]]' "$path" | sed "s|^|$rel:|" >> "$tmp_active_assumption_sites" || true
  grep -nE '^[[:space:]]*Abort\.' "$path" | sed "s|^|$rel:|" >> "$tmp_active_abort_sites" || true
done

global_admitted="$(find "$REPO_ROOT/02_FORMAL" -name "*.v" -type f -exec grep -Eh '^[[:space:]]*Admitted\.' {} + 2>/dev/null | wc -l | tr -d " ")"
global_axioms="$(find "$REPO_ROOT/02_FORMAL" -name "*.v" -type f -exec grep -Eh '^[[:space:]]*Axiom[[:space:]]+' {} + 2>/dev/null | wc -l | tr -d " ")"

# The deprecated proof archive is deliberately not published on the curated
# public branch. Global counts are always derived from THIS tree, so label
# the scope honestly: a curated tree's "global" excludes the archive.
if [ -d "$COQ_DIR/properties/_archive_deprecated" ]; then
  global_scope_suffix="(Includes Archived/Non-Active)"
  curated_tree_note=""
else
  global_scope_suffix="(This Tree — Deprecated Archive Not Published)"
  curated_tree_note="- NOTE: this is a curated tree; \`properties/_archive_deprecated/\` is deliberately not published. Counts above are derived from the published files only."
fi

{
  echo "# RIINA Proof Status"
  echo ""
  echo "This file is generated by \`scripts/update-proof-ledger.sh\`."
  echo "Do not edit this file manually."
  echo ""
  echo "## Active Build Snapshot"
  echo "- Coq files (active via \`_CoqProject\`): $active_files_count"
  echo "- Coq files (total in repository): $total_coq_files"
  echo "- Coq files (inactive or archived): $inactive_files_count"
  echo "- Qed proofs (active): $active_qed"
  echo "- Admitted (active): $active_admitted"
  echo "- Abort (active, incomplete proof attempts): $active_abort"
  echo "- Axioms (active, declared with \`Axiom\`): $active_axioms"
  echo "- \`Parameter\` declarations (active): $active_parameters  ← see TCB caveat below"
  echo "- Explicit semantic assumptions (active): $active_assumptions"
  echo ""
  echo "## Caveat: \`Parameter\` declarations are axioms in all but name"
  echo "In Coq a \`Parameter\` is logically equivalent to an \`Axiom\`. The active build"
  echo "contains **$active_parameters \`Parameter\` declarations**. The propositional ones"
  echo "(\`..._sound\`, \`..._correct\`, etc.) are the documented Trusted Hardware/Crypto"
  echo "Primitive interface — unproven by design because they model external physical"
  echo "measurements or opaque crypto functions, not Coq-provable facts (e.g."
  echo "\`domains/PhysicalSecurity.v\` EDA/X-ray/PUF/FIPS-140-3 entries; \`argon2id_hash\`"
  echo "in \`domains/VerifiedIdentity.v\`, RFC 9106). The headline \"Axioms (active) = 0\""
  echo "is therefore true only because these are spelled \`Parameter\`; they are tracked"
  echo "here separately and are NOT gated to 0."
  echo ""
  echo "## Active Abort Sites"
  if [ -s "$tmp_active_abort_sites" ]; then
    while IFS= read -r line; do
      echo "- \`$line\`"
    done < "$tmp_active_abort_sites"
  else
    echo "- None."
  fi
  echo ""
  echo "## Global Repository Snapshot $global_scope_suffix"
  echo "- Admitted (global): $global_admitted"
  echo "- Axioms (global): $global_axioms"
  if [ -n "$curated_tree_note" ]; then
    echo "$curated_tree_note"
  fi
  echo ""
  echo "## Policy"
  echo "- Production-active scope is defined by \`02_FORMAL/coq/_CoqProject\`."
  echo "- Production-active scope must keep:"
  echo "  - \`Admitted = 0\`"
  echo "  - \`Axioms = 0\`"
  echo "  - \`Explicit semantic assumptions = 0\`"
  echo "- \`Abort\` is surfaced for visibility but not gated; each entry is a known incomplete proof attempt to be tracked separately."
  echo ""
  echo "## Verification Commands"
  echo "\`\`\`bash"
  echo "bash scripts/update-proof-ledger.sh --check"
  echo "03_PROTO/target/release/riinac verify --full"
  echo "bash scripts/check-easier-gaps.sh"
  echo "\`\`\`"
} > "$tmp_status"

{
  echo "# RIINA Axiom Ledger"
  echo ""
  echo "This file is generated by \`scripts/update-proof-ledger.sh\`."
  echo "Do not edit this file manually."
  echo ""
  echo "## Active Build (_CoqProject)"
  echo "- Axioms: $active_axioms"
  echo "- Explicit semantic assumptions: $active_assumptions"
  echo ""
  echo "### Active Axiom Sites"
  if [ -s "$tmp_active_axiom_sites" ]; then
    while IFS= read -r line; do
      echo "- \`$line\`"
    done < "$tmp_active_axiom_sites"
  else
    echo "- None."
  fi
  echo ""
  echo "### Active Explicit Semantic Assumption Sites"
  if [ -s "$tmp_active_assumption_sites" ]; then
    while IFS= read -r line; do
      echo "- \`$line\`"
    done < "$tmp_active_assumption_sites"
  else
    echo "- None."
  fi
  echo ""
  echo "## Global Repository $global_scope_suffix"
  echo "- Axioms (global): $global_axioms"
  echo "- Admitted (global): $global_admitted"
  if [ -n "$curated_tree_note" ]; then
    echo "$curated_tree_note"
  fi
  echo ""
  echo "## Notes"
  echo "- Global non-zero values can exist in archived/non-active files."
  echo "- Public production claims must use active-build values only."
} > "$tmp_axioms"

if [ "$CHECK_MODE" -eq 1 ]; then
  diff -u "$REPO_ROOT/PROOF_STATUS.md" "$tmp_status" >/dev/null
  diff -u "$REPO_ROOT/AXIOMS.md" "$tmp_axioms" >/dev/null
  echo "Proof ledgers are up to date."
  exit 0
fi

cp "$tmp_status" "$REPO_ROOT/PROOF_STATUS.md"
cp "$tmp_axioms" "$REPO_ROOT/AXIOMS.md"
echo "Updated PROOF_STATUS.md and AXIOMS.md"
