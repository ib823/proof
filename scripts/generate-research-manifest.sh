#!/usr/bin/env bash
# ============================================================================
# generate-research-manifest.sh — regenerate 01_RESEARCH/00_METADATA/MANIFEST.md
#
# REQ-41: the manifest was a one-off snapshot (2026-01-11, "135 files") and went
# stale as the research corpus grew (now hundreds of files + the append-only
# 29_REFRESH_* batches). This regenerates it FROM THE TREE so it stays a faithful,
# reproducible inventory. Run it whenever the research corpus changes.
#
# Usage:  bash scripts/generate-research-manifest.sh [--check]
#   (no arg) rewrite MANIFEST.md
#   --check  exit 1 if MANIFEST.md is out of date (for a freshness gate)
# ============================================================================

set -euo pipefail

ROOT="$(git rev-parse --show-toplevel)"
RES="$ROOT/01_RESEARCH"
OUT="$RES/00_METADATA/MANIFEST.md"
CHECK=0
[ "${1:-}" = "--check" ] && CHECK=1

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

# Inventory all tracked files under 01_RESEARCH (deterministic: git-tracked,
# sorted), excluding the manifest itself so it does not chase its own size.
mapfile -t files < <(git -C "$ROOT" ls-files '01_RESEARCH/*' | grep -v '01_RESEARCH/00_METADATA/MANIFEST.md' | sort)

total_files="${#files[@]}"
total_bytes=0
total_lines=0
for f in "${files[@]}"; do
    p="$ROOT/$f"
    [ -f "$p" ] || continue
    total_bytes=$((total_bytes + $(wc -c <"$p")))
    total_lines=$((total_lines + $(wc -l <"$p")))
done
human_size="$(awk -v b="$total_bytes" 'BEGIN{ split("B KB MB GB",u); s=b; i=1; while(s>=1024 && i<4){s/=1024;i++} printf "%.1f%s", s, u[i] }')"

{
    echo "# TERAS RESEARCH TRACK — COMPLETE MANIFEST"
    echo ""
    echo "## Generation Metadata"
    echo ""
    echo "| Property | Value |"
    echo "|----------|-------|"
    echo "| Generated by | \`scripts/generate-research-manifest.sh\` (reproducible; REQ-41) |"
    echo "| Total Files | $total_files |"
    echo "| Total Size | $human_size |"
    echo "| Total Lines | $total_lines |"
    echo ""
    echo "> Regenerate with \`bash scripts/generate-research-manifest.sh\`; verify freshness"
    echo "> with \`--check\`. Counts are derived from git-tracked files under \`01_RESEARCH/\`"
    echo "> (excluding this manifest). The \`29_REFRESH_*\` batches are append-only currency"
    echo "> updates layered on the original lettered-domain corpus."
    echo ""
    echo "---"
    echo ""
    echo "## File Inventory by Directory"
    echo ""

    # Group by top-level subdirectory of 01_RESEARCH.
    prev_dir=""
    for f in "${files[@]}"; do
        rel="${f#01_RESEARCH/}"
        dir="${rel%%/*}"
        [ "$dir" = "$rel" ] && dir="(root)"
        if [ "$dir" != "$prev_dir" ]; then
            [ -n "$prev_dir" ] && echo ""
            echo "### $dir"
            echo ""
            echo "| Filename | Lines |"
            echo "|----------|-------|"
            prev_dir="$dir"
        fi
        base="${rel##*/}"
        lines=$(wc -l <"$ROOT/$f" 2>/dev/null || echo 0)
        echo "| \`$base\` | $lines |"
    done
} > "$tmp"

if [ "$CHECK" -eq 1 ]; then
    if diff -q "$OUT" "$tmp" >/dev/null 2>&1; then
        echo "[manifest] up to date ($total_files files)."
        exit 0
    fi
    echo "[manifest] STALE — run: bash scripts/generate-research-manifest.sh"
    exit 1
fi

cp "$tmp" "$OUT"
echo "[manifest] regenerated: $total_files files, $human_size, $total_lines lines."
