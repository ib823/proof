#!/usr/bin/env python3
# Generate the dependency-free UTS#39 confusables table (Rust) from the UCD
# security file confusables.txt. One-off; output is committed (Law 8).
import sys
mappings = {}  # source cp -> [target cps]
for line in open("/tmp/confusables.txt", encoding="utf-8"):
    line = line.split("#")[0].strip()
    if not line:
        continue
    parts = [p.strip() for p in line.split(";")]
    if len(parts) < 3 or parts[2] != "MA":
        continue
    src = int(parts[0], 16)
    tgt = [int(x, 16) for x in parts[1].split()]
    mappings[src] = tgt

items = sorted(mappings.items())
payload, index = [], []
for cp, seq in items:
    index.append((cp, len(payload), len(seq)))
    payload.extend(seq)

out = []
out.append("// Copyright (c) 2026 The RIINA Authors. All rights reserved.")
out.append("// GENERATED by scripts/gen_confusables.py from UCD security")
out.append("// confusables.txt 17.0.0. Do not edit by hand. Dependency-free vendored")
out.append("// Unicode security data (Law 8): the UTS#39 confusable prototype mapping,")
out.append("// sorted by source code point for binary search.")
out.append("#![cfg_attr(rustfmt, rustfmt::skip)]")
out.append("")
out.append(f"/// `(source, offset into CONFUSABLE_DATA, length)` ({len(index)} entries).")
out.append("pub static CONFUSABLE_INDEX: &[(u32, u32, u8)] = &[")
out.append("".join(f"({cp:#x},{o},{l})," for cp, o, l in index))
out.append("];")
out.append("pub static CONFUSABLE_DATA: &[u32] = &[")
out.append("".join(f"{cp:#x}," for cp in payload))
out.append("];")
out.append("")
sys.stdout.write("\n".join(out))
