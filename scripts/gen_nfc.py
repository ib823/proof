#!/usr/bin/env python3
# Generate dependency-free NFC tables (Rust) from the UCD. One-off; output is
# committed so there is no build-time or third-party dependency (Law 8).
import sys

UNIDATA = "/tmp/ucd_UnicodeData.txt"
EXCL = "/tmp/ucd_CompositionExclusions.txt"

ccc = {}          # cp -> combining class (non-zero only)
decomp1 = {}      # cp -> [cps]   single-step CANONICAL decomposition
for line in open(UNIDATA):
    f = line.rstrip("\n").split(";")
    if len(f) < 6: continue
    cp = int(f[0], 16)
    if f[3] != "0":
        ccc[cp] = int(f[3])
    d = f[5]
    if d and not d.startswith("<"):   # canonical only (compatibility has a <tag>)
        decomp1[cp] = [int(x, 16) for x in d.split()]

# Full canonical decomposition (recursive).
def full(cp, seen=None):
    if cp not in decomp1:
        return [cp]
    out = []
    for c in decomp1[cp]:
        out.extend(full(c))
    return out

decomp_full = {cp: full(cp) for cp in decomp1}

# Composition exclusions: explicit list + singletons + non-starter decomps.
excl = set()
for line in open(EXCL):
    line = line.split("#")[0].strip()
    if line:
        excl.add(int(line, 16))
for cp, d in decomp1.items():
    if len(d) == 1:                       # singleton
        excl.add(cp)
    elif ccc.get(d[0], 0) != 0:           # non-starter first element
        excl.add(cp)

# Canonical composition pairs: (a,b) -> cp for length-2, non-excluded decomps.
compose = {}
for cp, d in decomp1.items():
    if cp in excl or len(d) != 2:
        continue
    compose[(d[0], d[1])] = cp

def emit():
    out = []
    out.append("// Copyright (c) 2026 The RIINA Authors. All rights reserved.")
    out.append("// GENERATED by scripts/gen_nfc.py from UCD UnicodeData.txt 17.0.0 +")
    out.append("// CompositionExclusions.txt. Do not edit by hand. Dependency-free")
    out.append("// vendored Unicode data (Law 8): canonical decomposition, combining")
    out.append("// classes, and canonical composition pairs, sorted for binary search.")
    out.append("#![cfg_attr(rustfmt, rustfmt::skip)]")
    out.append("")
    # CCC: sorted (cp, class)
    items = sorted(ccc.items())
    out.append(f"/// Non-zero canonical combining classes, sorted by code point ({len(items)}).")
    out.append("pub static COMBINING_CLASS: &[(u32, u8)] = &[")
    out.append("".join(f"({cp:#x},{c})," for cp, c in items))
    out.append("];")
    out.append("")
    # Decomposition: flattened. Store (cp, start, len) into a shared payload array.
    items = sorted(decomp_full.items())
    payload = []
    index = []
    for cp, seq in items:
        index.append((cp, len(payload), len(seq)))
        payload.extend(seq)
    out.append(f"/// Fully-applied canonical decompositions ({len(index)} entries).")
    out.append("/// `(code point, offset into DECOMP_DATA, length)`, sorted by code point.")
    out.append("pub static DECOMP_INDEX: &[(u32, u32, u8)] = &[")
    out.append("".join(f"({cp:#x},{o},{l})," for cp, o, l in index))
    out.append("];")
    out.append("pub static DECOMP_DATA: &[u32] = &[")
    out.append("".join(f"{cp:#x}," for cp in payload))
    out.append("];")
    out.append("")
    # Composition: sorted by (a,b)
    items = sorted(compose.items())
    out.append(f"/// Canonical composition pairs `((first, second), composed)` ({len(items)}),")
    out.append("/// sorted by `(first, second)`; excludes the composition-exclusion set.")
    out.append("pub static COMPOSE: &[(u32, u32, u32)] = &[")
    out.append("".join(f"({a:#x},{b:#x},{cp:#x})," for (a, b), cp in items))
    out.append("];")
    out.append("")
    return "\n".join(out)

sys.stdout.write(emit())
